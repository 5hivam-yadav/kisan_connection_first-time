const generatePriceHistory = (baseMin, baseMax, baseAvg, trend = 'up') => {
  const points = [];
  const days = 30;
  for (let i = days - 1; i >= 0; i--) {
    const d = new Date();
    d.setDate(d.getDate() - i);
    const dateStr = d.toLocaleDateString('en-GB', { day: '2-digit', month: 'short' });
    const variance = (Math.sin(i / 3) * 0.08) + ((days - i) * (trend === 'up' ? 0.003 : -0.003));
    const modal = Math.round(baseAvg * (1 + variance));
    const min = Math.round(baseMin * (1 + variance * 0.8));
    const max = Math.round(baseMax * (1 + variance * 1.1));
    const plat = Math.round(modal * 0.98);
    const demand = Math.min(95, Math.max(40, Math.round(75 + variance * 100)));
    points.push({
      date: dateStr,
      minPrice: min,
      maxPrice: max,
      modalPrice: modal,
      platformAvg: plat,
      demandIndex: demand
    });
  }
  return points;
};

